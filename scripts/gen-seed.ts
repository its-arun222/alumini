// Generates supabase/seed.sql from src/data/mockData.ts
// Run: npx tsx scripts/gen-seed.ts
import { writeFileSync } from 'node:fs';
import { CURRENT_STUDENT, ALUMNI_DATA, INITIAL_OPPORTUNITIES, INITIAL_MENTORSHIP_REQUESTS, INITIAL_PENDING_UPDATES } from '../src/data/mockData';

const snake = (k: string) => k.replace(/[A-Z]/g, (c) => '_' + c.toLowerCase());
const lit = (v: unknown): string => {
  if (v === undefined || v === null) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
function insert(table: string, rows: Record<string, any>[]) {
  const cols = Object.keys(rows[0]).map(snake);
  const values = rows.map((r) => '  (' + Object.keys(rows[0]).map((k) => lit(r[k])).join(', ') + ')').join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict (id) do nothing;\n`;
}
// make every row use the same key set (optional fields -> null)
const norm = (rows: Record<string, any>[]) => {
  const keys = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  return rows.map((r) => Object.fromEntries(keys.map((k) => [k, r[k] ?? null])));
};

const sql = [
  '-- Generated by scripts/gen-seed.ts. Safe to re-run.',
  insert('students', norm([CURRENT_STUDENT as any])),
  insert('alumni', norm(ALUMNI_DATA as any)),
  insert('opportunities', norm(INITIAL_OPPORTUNITIES as any)),
  insert('mentorship_requests', norm(INITIAL_MENTORSHIP_REQUESTS as any)),
  insert('pending_profile_updates', norm(INITIAL_PENDING_UPDATES as any)),
].join('\n');
writeFileSync('supabase/seed.sql', sql);
console.log('wrote supabase/seed.sql');
