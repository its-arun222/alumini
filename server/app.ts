import express from 'express';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';
import { registerDbRoutes } from './db';

dotenv.config();

const app = express();

app.use(express.json({ limit: '10mb' }));

registerDbRoutes(app);

function generateMaitFallbackGuidance(profile: any, question: string): string {
  const name = profile?.name || 'Aarav';
  const semester = profile?.currentSemester || 6;
  const skills = profile?.skills?.join(', ') || 'C++, React, Node.js, Distributed Systems';
  const companies = profile?.dreamCompanies?.join(', ') || 'Google, Microsoft, Blinkit, Sprinklr';

  return `### 🎯 Strategic Verdict for ${name} (MAIT CST, Semester ${semester})

Your current profile with skills in **${skills}** puts you in a strong tier for product-based roles at **${companies}**. Because MAIT is in Delhi NCR and has a massive network of alumni in Gurugram, Bengaluru, and Noida, combining solid DSA with real system design projects is your highest-ROI playbook.

---

### 🚀 30-60-90 Day Action Blueprint

1. **Next 30 Days (Core DSA & Problem Solving):**
   - Focus on blind-75 and NeetCode 150 (specifically Graphs, Dynamic Programming, and Heaps in C++/Java).
   - Aim for consistent contest rating (1600+ on LeetCode or Codeforces Specialist).

2. **60-Day Milestone (High-Scale Project & System Design):**
   - Build a distributed key-value store, real-time order matching engine, or telemetry ingest pipeline in Go/Java.
   - Deploy on AWS/GCP with Docker and measure throughput under concurrency.

3. **90-Day Referral Strategy:**
   - Connect with MAIT CST alumni (such as Priya Goel at Google Cloud or Rohan Verma at Blinkit) through the **MAIT Mentorship Hub**.
   - Request a targeted 1:1 resume review rather than a cold referral; alumni love seeing MAIT juniors with GitHub proofs of work.

---

### 💡 High-Yield Resources for MAIT Students
- **System Design:** Alex Xu Vol 1 & 2 + Martin Kleppmann's *Designing Data-Intensive Applications*.
- **MAIT Placement Drives:** Target both on-campus Day-1/Super-Dream slots and off-campus early career referral portals opening in July/August.

*Note: This response was generated by the MAIT CST AI Counselor.*`;
}

// Stateless AI Career Guidance Chatbot endpoint
app.post('/api/career-guidance', async (req, res) => {
  try {
    const { profile, question } = req.body;
    if (!question || typeof question !== 'string' || question.trim().length === 0) {
      return res.status(400).json({ error: 'Question is required' });
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      const fallbackAdvice = generateMaitFallbackGuidance(profile, question);
      return res.json({
        answer: fallbackAdvice,
        isFallback: true,
        note: 'Running in resilient offline mode. Set GEMINI_API_KEY for live Gemini 3.8 Flash inferences.',
      });
    }

    const ai = new GoogleGenAI();
    const systemInstruction = `You are the official Senior AI Career & Placement Counselor for Maharaja Agrasen Institute of Technology (MAIT), Rohini, Delhi (affiliated with GGSIPU), specifically dedicated to the Department of Computer Science & Technology (CST).

CRITICAL ARCHITECTURE:
- This counseling session is strictly STATELESS: You evaluate the student's current profile snapshot and this specific question alone. No chat history is maintained.
- Speak with high expertise in the Indian engineering college context, GGSIPU grading/curriculum quirks, Delhi NCR tech hub dynamics (Gurugram/Noida), tier-1 off-campus referral realities (Google, Microsoft, Amazon, Sprinklr, Blinkit, Zomato, Goldman Sachs), and practical advice on balancing semesters with LeetCode/DSA, System Design, and Open Source.

Format your response cleanly with clear markdown sections:
1. 🎯 Direct Verdict & Strategic Assessment
2. 🚀 Step-by-Step Action Plan (30-60-90 Days)
3. 💡 High-Yield Resources & Project Ideas for MAIT CST Students
4. 🤝 Recommended MAIT Alumni Pathways (e.g. connecting with MAIT CST alumni at Google, Blinkit, Microsoft, or Goldman Sachs).

Keep it structured, concise, actionable, and encouraging.`;

    const prompt = `STUDENT PROFILE SNAPSHOT:
Name: ${profile?.name || 'Aarav Sharma'}
College: Maharaja Agrasen Institute of Technology (MAIT), Delhi
Branch: ${profile?.branch || 'Computer Science & Technology (CST)'}
Semester: ${profile?.currentSemester || 6} (Batch ${profile?.batchYear || '2022-2026'})
CGPA: ${profile?.cgpa || 8.84}
Current Technical Skills: ${(profile?.skills || []).join(', ') || 'C++, React, Node.js, Distributed Systems'}
Interests: ${(profile?.interests || []).join(', ') || 'High-Scale Backend, Cloud'}
Target / Dream Companies: ${(profile?.dreamCompanies || []).join(', ') || 'Google, Microsoft, Blinkit, Sprinklr'}

STUDENT'S QUESTION:
"${question}"

Provide targeted, high-impact career advice tailored to this MAIT CST student.`;

    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
      config: {
        systemInstruction,
        temperature: 0.7,
      },
    });

    const text = response.text || generateMaitFallbackGuidance(profile, question);
    return res.json({
      answer: text,
      isFallback: false,
    });
  } catch (error: any) {
    console.error('Error generating career guidance via Gemini API:', error);
    const fallbackAdvice = generateMaitFallbackGuidance(req.body?.profile, req.body?.question || '');
    return res.json({
      answer: fallbackAdvice,
      isFallback: true,
      errorDetails: error?.message,
    });
  }
});

export default app;
